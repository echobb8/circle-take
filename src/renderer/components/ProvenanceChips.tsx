import type { Provenance } from '@shared/types'
import { Icon } from './Icon'

/**
 * The recipe, in chips: which generator, which model version, which seed, what
 * it cost. Every failing shot in the Print room has to carry enough of this to
 * be re-run exactly — so provenance is never hidden behind a disclosure.
 */

export interface ProvenanceChipsProps {
  provenance: Provenance
  /** $ cost of this generation, when the project has a rate card. */
  cost?: number | null
  compact?: boolean
  /** Highlight the model chip (model-mix warning on the shot). */
  modelWarn?: boolean
}

export function formatUsd(v: number): string {
  return v >= 100 ? `$${Math.round(v)}` : `$${v.toFixed(2)}`
}

export function ProvenanceChips({
  provenance,
  cost,
  compact = false,
  modelWarn = false,
}: ProvenanceChipsProps): JSX.Element {
  const { generator, model, seed } = provenance
  return (
    <span className={`prov-chips${compact ? ' is-compact' : ''}`}>
      {generator && (
        <span className="chip chip-gen" title={`Generator: ${generator}`}>
          {generator}
        </span>
      )}
      {model && !compact && (
        <span
          className={`chip chip-model mono${modelWarn ? ' is-warn' : ''}`}
          title={modelWarn ? `Model ${model} — this shot mixes model versions` : `Model: ${model}`}
        >
          {model}
        </span>
      )}
      {seed && (
        <span className="chip chip-seed mono" title={`Seed: ${seed}`}>
          <span className="chip-key caps">seed</span>
          {seed}
        </span>
      )}
      {cost != null && cost > 0 && (
        <span className="chip chip-cost mono" title="Generation cost from the project rate card">
          <Icon name="coin" size={11} />
          {formatUsd(cost)}
        </span>
      )}
    </span>
  )
}

/** The amber "this shot was generated by more than one model" warning. */
export function ModelMixChip({ models }: { models: string[] }): JSX.Element | null {
  if (models.length < 2) return null
  return (
    <span
      className="chip chip-mix"
      title={`Model-version drift breaks reproducibility — this shot mixes: ${models.join(', ')}`}
    >
      <Icon name="alert" size={11} />
      {models.length} MODELS
    </span>
  )
}
